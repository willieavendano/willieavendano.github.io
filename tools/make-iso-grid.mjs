#!/usr/bin/env node
// Generates a true-scale isometric grid SVG (user units = inches).
//   node tools/make-iso-grid.mjs [widthIn=7] [heightIn=8.5] [out=engineering-fundamentals/resources/iso-grid.svg]
// Lattice points are 0.25 in apart along all three isometric axes (vertical,
// +30°, -30°). Every 2nd line in each family is heavier (1 in at ½ scale).
// One <path> per stroke weight; segments are clipped analytically to the sheet.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const W = Number(process.argv[2] ?? 7);
const H = Number(process.argv[3] ?? 8.5);
const out = path.resolve(root, process.argv[4] ?? 'engineering-fundamentals/resources/iso-grid.svg');

const S = 0.25;                       // spacing along each isometric axis (in)
const D = S * Math.cos(Math.PI / 6);  // horizontal gap between vertical lines
const T = Math.tan(Math.PI / 6);      // slope of the 30° families
const X0 = W / 2;                     // lattice origin: bottom-center,
const Y0 = H - 2 * S;                 //   on heavy lines of all three families

const LIGHT = { color: '#BDD4E7', width: 0.006 };
const HEAVY = { color: '#8FB3D6', width: 0.01 };
const f = n => (Math.round(n * 1e4) / 1e4).toString();
const light = [], heavy = [];

// Clip the line y = a + m·x to the rectangle [0,W]×[0,H]; returns segment or null.
function clipLine(a, m) {
  let x1 = 0, x2 = W;
  if (m !== 0) {
    const xa = (0 - a) / m, xb = (H - a) / m;
    x1 = Math.max(x1, Math.min(xa, xb));
    x2 = Math.min(x2, Math.max(xa, xb));
  } else if (a < 0 || a > H) return null;
  if (x2 - x1 < 1e-6) return null;
  return [x1, a + m * x1, x2, a + m * x2];
}
const seg = ([x1, y1, x2, y2]) => `M${f(x1)} ${f(y1)}L${f(x2)} ${f(y2)}`;
const even = n => ((n % 2) + 2) % 2 === 0;

const N = Math.ceil((W + H) / D) + 4;
for (let i = -N; i <= N; i++) {            // vertical lines: x = X0 + i·D
  const x = X0 + i * D;
  if (x < 0 || x > W) continue;
  (even(i) ? heavy : light).push(`M${f(x)} 0V${f(H)}`);
}
for (let j = -N * 2; j <= N * 2; j++) {    // -30° (falls left→right): y = Y0 + j·S + (x−X0)·T
  const s = clipLine(Y0 + j * S - X0 * T, T);
  if (s) (even(j) ? heavy : light).push(seg(s));
}
for (let k = -N * 2; k <= N * 2; k++) {    // +30° (rises left→right): y = Y0 + k·S − (x−X0)·T
  const s = clipLine(Y0 + k * S + X0 * T, -T);
  if (s) (even(k) ? heavy : light).push(seg(s));
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}in" height="${H}in" viewBox="0 0 ${W} ${H}">
<!-- Isometric grid: 0.25 in along each axis; heavy every 2nd line. Generated by tools/make-iso-grid.mjs -->
<rect width="${W}" height="${H}" fill="#fff"/>
<path fill="none" stroke="${LIGHT.color}" stroke-width="${LIGHT.width}" d="${light.join('')}"/>
<path fill="none" stroke="${HEAVY.color}" stroke-width="${HEAVY.width}" d="${heavy.join('')}"/>
<rect x="${LIGHT.width / 2}" y="${LIGHT.width / 2}" width="${f(W - LIGHT.width)}" height="${f(H - LIGHT.width)}" fill="none" stroke="${LIGHT.color}" stroke-width="${LIGHT.width}"/>
</svg>
`;
fs.writeFileSync(out, svg);
console.log(`wrote ${path.relative(root, out)} (${W}×${H} in, ${light.length} light + ${heavy.length} heavy lines, ${(svg.length / 1024).toFixed(1)} KB)`);
